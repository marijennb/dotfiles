-- =========================
-- Editor Settings
-- =========================

local opt = vim.opt

-- Line numbers
opt.number = true
opt.relativenumber = true

-- Cursor
opt.cursorline = true

-- Colors
opt.termguicolors = true

-- Mouse support
opt.mouse = "a"

-- Tabs & indentation
opt.tabstop = 4
opt.shiftwidth = 4
opt.expandtab = true
opt.smartindent = true

-- Search behavior
opt.ignorecase = true
opt.smartcase = true

-- Better scrolling feel
opt.scrolloff = 8

-- Faster updates
opt.updatetime = 250

-- Disable swap files (optional)
opt.swapfile = false
